// Post-deploy acceptance for https://sub.fakeyou.eu.org.
//
// Runs in the Deploy workflow on the exact workspace that was just built, so it can
// compare the deployed site against the asset map and source archive the build
// produced. Every check is read-only: no publication is created and nothing is
// written to KV. `GITHUB_SHA` is required so a stale deployment can never pass.
//
// The checks live in an exported function so test/deployment-contract.test.mjs can
// run them against src/worker.js and prove they fail on a broken deployment.
import {gunzipSync} from 'node:zlib';
import {pathToFileURL} from 'node:url';

const healthUrl = 'https://sub.fakeyou.eu.org/api/health';
const DEFAULT_BASE = new URL(healthUrl).origin;

// Every probe below is also asserted against public/index.html in
// test/deployment-contract.test.mjs, so a probe can never silently go stale.
const HOME_PROBES = ['id="convert-form"', 'id="source-input"', 'id="theme-toggle"', 'id="about-dialog"', 'id="publish"', 'src="./theme.js"'];
const CSP_RULES = ["default-src 'self'", "script-src 'self'", "frame-ancestors 'none'", "base-uri 'none'", "object-src 'none'"];
const ASSET_PROBES = [['/app.js', 'javascript'], ['/style.css', 'css'], ['/converter.js', 'javascript'], ['/theme.js', 'javascript']];
const ARCHIVE_ENTRIES = ['LICENSE', 'NOTICE.md', 'src/worker.js', 'src/converter.js', 'public/index.html', 'public/theme.js', 'package-lock.json'];

export async function verifyLive({base = process.env.BASE_URL || DEFAULT_BASE, expectedRevision = process.env.GITHUB_SHA, fetchImpl = globalThis.fetch, assets, log = console.log, attempts = 12, retryDelayMs = 5000} = {}) {
  base = String(base).replace(/\/+$/, '');
  if (!expectedRevision) throw Error('GITHUB_SHA is required');
  if (new URL(healthUrl).origin !== base) throw Error('BASE_URL must match the deployed custom domain');
  const get = (path, options = {}) =>
    fetchImpl(base + path, {redirect: 'manual', ...options, signal: AbortSignal.timeout(12000), headers: {'Cache-Control': 'no-cache', ...options.headers}});
  const fail = (message) => {
    throw Error(message);
  };

  // -------------------------------------------------------------- 1. revision
  let healthy = false;
  for (let attempt = 0; attempt < attempts; attempt++) {
    try {
      const response = await get('/api/health');
      const data = await response.json();
      if (response.ok && data.ok && data.revision === expectedRevision) {
        healthy = true;
        break;
      }
    } catch {}
    if (attempt < attempts - 1 && retryDelayMs > 0) await new Promise((r) => setTimeout(r, retryDelayMs));
  }
  if (!healthy) fail('Live revision was not confirmed; inspect this workflow and Cloudflare deployment');
  log('Live revision verified: ' + expectedRevision);

  // ----------------------------------------------------- 2. homepage contract
  const home = await get('/');
  if (home.status !== 200 || !home.headers.get('content-type')?.includes('text/html')) fail('Homepage unavailable');
  const html = await home.text();
  for (const probe of HOME_PROBES) {
    if (!html.includes(probe)) fail('Homepage markup missing ' + probe);
  }
  const csp = home.headers.get('content-security-policy') || '';
  for (const rule of CSP_RULES) {
    if (!csp.includes(rule)) fail('CSP missing: ' + rule);
  }
  if (home.headers.get('x-content-type-options') !== 'nosniff') fail('Missing nosniff');
  if (!home.headers.get('referrer-policy')) fail('Missing referrer policy');
  if ((home.headers.get('x-frame-options') || '').toUpperCase() !== 'DENY') fail('Missing X-Frame-Options: DENY');
  log('Homepage markup and security headers verified');

  // ------------------------------------------------------------- 3. assets
  // Static assets are served from the tested build; a stale or missing asset must
  // fail here. The asset map is generated by walking public/, so this loop also
  // catches a public file that the build forgot to map.
  for (const [path, type] of ASSET_PROBES) {
    const response = await get(path, {method: 'HEAD'});
    if (response.status !== 200) fail('Asset unavailable: ' + path);
    if (!(response.headers.get('content-type') || '').includes(type)) fail('Asset content-type mismatch: ' + path);
  }
  const appScript = await get('/app.js');
  if (!(await appScript.text()).includes('convertSources')) fail('/app.js does not look like the built UI script');

  let expectedAssets = assets;
  if (!expectedAssets) {
    try {
      expectedAssets = (await import('../src/assets.generated.js')).default;
    } catch {
      fail('src/assets.generated.js is missing; run npm run build before verify-live.mjs');
    }
  }
  for (const [path, asset] of Object.entries(expectedAssets)) {
    const response = await get(path, {method: 'HEAD'});
    if (response.status !== 200) fail('Deployed asset unavailable: ' + path);
    const type = (response.headers.get('content-type') || '').split(';')[0].trim();
    if (type !== asset.type.split(';')[0].trim()) fail(`Deployed content-type mismatch for ${path}: ${type} != ${asset.type}`);
  }
  // Resources the shipped page references must be served too (a new <script> or
  // <link> pointing at an unmapped file is exactly the silent 404 this guards).
  for (const match of html.matchAll(/(?:src|href)="\.\/([\w./-]+)"/g)) {
    const response = await get('/' + match[1], {method: 'HEAD'});
    if (response.status !== 200) fail(`index.html references ./${match[1]} which is not served (${response.status})`);
  }
  log(`Static assets verified (${Object.keys(expectedAssets).length} mapped files plus page references)`);

  // ------------------------------------------------ 4. AGPL source archive
  const source = await get('/source.tar.gz');
  if (source.status !== 200 || !source.headers.get('content-type')?.includes('gzip')) fail('AGPL source archive unavailable');
  const rawArchive = new Uint8Array(await source.arrayBuffer());
  if (rawArchive[0] !== 0x1f || rawArchive[1] !== 0x8b) fail('AGPL source archive is not gzip');
  let entries;
  try {
    entries = gunzipSync(rawArchive).toString('latin1');
  } catch {
    fail('AGPL source archive is not valid gzip');
  }
  for (const required of ARCHIVE_ENTRIES) {
    if (!entries.includes(required)) fail('AGPL source archive is missing ' + required);
  }
  if (!entries.includes('ustar')) fail('AGPL source archive is not a tar stream');
  log('Static assets, security headers and source archive verified');

  // ---------------------------------------------------------- 5. API guards
  const method = await get('/api/fetch');
  if (method.status !== 405 || (method.headers.get('allow') || '') !== 'POST') fail('api/fetch must reject GET with 405 and Allow: POST');
  const crossSite = await get('/api/fetch', {method: 'POST', headers: {'Content-Type': 'application/json', Origin: 'https://example.invalid'}, body: JSON.stringify({url: 'https://example.com/sub'})});
  if (crossSite.status !== 403) fail('Cross-origin api/fetch must be rejected');
  const invalid = await get('/api/fetch', {method: 'POST', headers: {'Content-Type': 'application/json', Origin: base}, body: JSON.stringify({url: 'not-a-url'})});
  if (invalid.status !== 422) fail('Invalid source URL must be rejected with 422');
  const missing = await get('/api/unknown');
  if (missing.status !== 404) fail('Unknown API must return 404');
  log('API guards verified');

  // ---------------------------------------------- 6. hosted short links
  // Hosted links are permanent by default (no KV expirationTtl), so this probe must
  // not rely on any record expiring: it uses a token that was never published and a
  // cross-origin request that the Worker rejects before touching storage. Nothing
  // here creates, updates or deletes a KV record.
  const short = await get('/s/AAAAAAAA');
  if (short.status !== 404) fail('Unknown short link must return 404');
  const shortType = short.headers.get('content-type') || '';
  if (!shortType || shortType.includes('text/html')) fail('Unknown short link must not serve the HTML app shell (content-type: ' + shortType + ')');
  const shortBody = await short.text();
  if (/<!doctype html|<html/i.test(shortBody)) fail('Unknown short link must not return an HTML page');
  const shortCache = (short.headers.get('cache-control') || '').toLowerCase();
  if (shortCache.includes('public') || !shortCache.includes('no-store')) fail('Unknown short link must be private and non-cacheable (cache-control: ' + shortCache + ')');

  const shortHead = await get('/s/AAAAAAAA', {method: 'HEAD'});
  if (shortHead.status !== 404) fail('HEAD on an unknown short link must return 404');

  const shortShape = await get('/s/not-a-token');
  if (shortShape.status !== 404) fail('A malformed short link token must return 404');
  if ((await get('/s/AAAAAAAA/extra')).status !== 404) fail('A short link with a path suffix must return 404');

  // Publishing must stay origin-guarded, and must be rejected before any KV write.
  const publishMethod = await get('/api/publish');
  if (publishMethod.status !== 405 || (publishMethod.headers.get('allow') || '') !== 'POST') fail('api/publish must reject GET with 405 and Allow: POST');
  const publishCross = await get('/api/publish', {method: 'POST', headers: {'Content-Type': 'application/json', Origin: 'https://example.invalid'}, body: JSON.stringify({content: 'x', target: 'Surge'})});
  if (publishCross.status !== 403) fail('Cross-origin api/publish must be rejected before storing anything');
  if (/[0-9a-f]{64}/.test(await publishCross.text())) fail('Rejected publish must not leak a manage token');
  const revokeCross = await get('/api/publish/AAAAAAAA', {method: 'DELETE', headers: {Origin: 'https://example.invalid'}});
  if (revokeCross.status !== 403) fail('Cross-origin revoke must be rejected before touching KV');
  log('Hosted short link guard verified');
  log('Deployment verification passed');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await verifyLive();
